// icons_v4.h - 1-bit UI icons for the event log screen (20x20 set)
//
// FORMAT
//   - 1 bit per pixel, MSB-first (leftmost pixel = bit 7 of each byte)
//   - 1 = draw a pixel (any draw colour), 0 = leave unchanged
//   - Rows are padded to whole bytes: bytes_per_row = (width + 7) / 8,
//     padding bits are 0. For these 20 px wide icons that is 3 bytes per
//     row, 60 bytes per icon (the last 4 bits of each row's 3rd byte are 0).
//   - Array names end in _<W>x<H>. Needs C++ (constexpr, 0b literals).
//
// SIZES
//   All 13 icons are 20x20, and each pair / battery set shares the same
//   frame, so they can be drawn at the same x/y with no offset.
//
// NAMING
//   *_on = normal state, *_off = crossed-out / disabled state
//   battery_*: empty < low < half < full, plus charging (wave symbol)

